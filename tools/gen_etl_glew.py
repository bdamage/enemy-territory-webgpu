#!/usr/bin/env python3
"""Generate etl/web/GL/glew.h: a stand-in for GLEW that routes the ET: Legacy
renderer's gl* calls to the WebGPU GL emulation (web/wgl_*.c).

- Functions the emulation implements (wg* in web/qgl_wgpu.h) are mapped 1:1.
- Everything else the renderer references (framebuffer objects, GLSL
  programs, debug output, ...) is only reachable behind GLEW extension
  checks that report "unsupported", so those become no-op macros. That
  also guarantees nothing falls through to Emscripten's WebGL library.
"""
import os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
wg = set(re.findall(r'#define qgl(\w+) wg\1', open(os.path.join(root, 'web/qgl_wgpu.h')).read()))

used = set()
for d in ('etl/src/renderer', 'etl/src/renderercommon'):
    for f in os.listdir(os.path.join(root, d)):
        if f.endswith(('.c', '.h')):
            src = open(os.path.join(root, d, f), encoding='latin-1').read()
            used |= set(re.findall(r'\b(gl[A-Z]\w*)\s*\(', src))

# extension/variant names that map onto an implemented base function
alias = {
    'glDepthRangef': 'DepthRange', 'glClearDepthf': 'ClearDepth', 'glOrthof': 'Ortho',
    'glActiveTexture': 'ActiveTextureARB', 'glClientActiveTexture': 'ClientActiveTextureARB',
    'glMultiTexCoord2f': 'MultiTexCoord2fARB',
}
# stubs whose result is used
returns = {
    'glCheckFramebufferStatusEXT': '0x8CD5',  # GL_FRAMEBUFFER_COMPLETE
    'glCheckFramebufferStatus': '0x8CD5',
    'glCreateShaderObjectARB': '0', 'glCreateProgramObjectARB': '0', 'glCreateShader': '0',
    'glCreateProgram': '0', 'glGetUniformLocation': '(-1)', 'glGetUniformLocationARB': '(-1)',
    'glGetStringi': '((const GLubyte *)"")', 'glIsTexture': '0', 'glGetAttribLocation': '(-1)',
}
skip = {'glConfig', 'glConfig2', 'glState', 'glMatrix', 'glConfigString', 'glWrapClampMode',
        'glStateBits', 'glFog', 'glewInit', 'glewIsSupported', 'glewGetString', 'glewGetErrorString'}

out = ['/* Generated by tools/gen_etl_glew.py -- do not edit.',
       ' * GLEW stand-in for the ET: Legacy renderer on the WebGPU GL emulation. */',
       '#ifndef __ETL_WEB_GLEW_H__', '#define __ETL_WEB_GLEW_H__', '',
       '#include <GL/gl.h>', '#include <GL/glext.h>',
       '#include "qgl_wgpu.h"', '',
       '#ifndef GLAPIENTRY', '#define GLAPIENTRY', '#endif',
       '',
       '/* GLEW API */',
       '#define GLEW_OK 0', '#define GLEW_ERROR_NO_GLX_DISPLAY 4', '#define GLEW_VERSION 1',
       '#define glewInit() GLEW_OK', '#define glewIsSupported( x ) 0',
       '#define glewGetString( x ) ((const GLubyte *)"WebGPU")',
       '#define glewGetErrorString( x ) ((const GLubyte *)"")',
       'static unsigned char glewExperimental;', '',
       '/* extensions the emulation provides */',
       '#define GLEW_ARB_multitexture 1', '#define GLEW_EXT_texture_env_add 1',
       '#define GLEW_EXT_texture_filter_anisotropic 1', '#define GLEW_ARB_texture_non_power_of_two 1',
       '#define GLEW_EXT_compiled_vertex_array 1', '',
       '/* everything else is unsupported */',
       '#define GLEW_ARB_texture_compression 0', '#define GLEW_EXT_texture_compression_s3tc 0',
       '#define GLEW_S3_s3tc 0', '#define GLEW_ARB_framebuffer_object 0',
       '#define GLEW_EXT_framebuffer_multisample 0', '#define GLEW_ARB_fragment_program 0',
       '#define GLEW_ARB_shader_objects 0', '#define GLEW_ARB_vertex_shader 0',
       '#define GLEW_ARB_fragment_shader 0', '#define GLEW_ARB_occlusion_query 0',
       '#define GLEW_ARB_debug_output 0', '#define GLEW_KHR_debug 0',
       '#define GLEW_NV_fog_distance 0', '#define GLEW_ATI_pn_triangles 0', '']

mapped, stubbed = [], []
for name in sorted(used):
    if name in skip or name.startswith('glew'):
        continue
    base = alias.get(name, name[2:])
    if base in wg:
        out.append(f'#define {name} wg{base}')
        mapped.append(name)
    else:
        val = returns.get(name, '((void)0)')
        out.append(f'#define {name}( ... ) {val}')
        stubbed.append(name)
out += ['', '#endif', '']
dst = os.path.join(root, 'etl/web/GL')
os.makedirs(dst, exist_ok=True)
open(os.path.join(dst, 'glew.h'), 'w').write('\n'.join(out))
print(f'{len(mapped)} mapped, {len(stubbed)} stubbed: {" ".join(stubbed)}', file=sys.stderr)
