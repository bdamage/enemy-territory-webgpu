#!/bin/sh
# usage: gen_prefix.sh <llvm-nm> <module> <objs...>
# Emits a header that #defines every global symbol defined by the module's
# objects to <module>__<symbol>, so several game modules can share one binary.
NM="$1"; MOD="$2"; shift 2
echo "/* generated by tools/gen_prefix.sh for module '$MOD' -- do not edit */"
echo "#ifndef __PREFIX_${MOD}_H__"
echo "#define __PREFIX_${MOD}_H__"
"$NM" -g --defined-only --format=just-symbols "$@" 2>/dev/null \
  | grep -E '^[A-Za-z_][A-Za-z0-9_]*$' \
  | grep -v -E '^(main|__.*)$' \
  | sort -u \
  | awk -v m="$MOD" '{ printf "#define %s %s__%s\n", $1, m, $1 }'
echo "#endif"
