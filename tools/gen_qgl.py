#!/usr/bin/env python3
"""Generate web/qgl_wgpu.h: maps every qgl* entry point declared in
src/renderer/qgl.h onto a wg* function implemented by the WebGPU GL layer."""
import re, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'src/renderer/qgl.h'), encoding='latin-1').read()
out = ["// Generated by tools/gen_qgl.py -- do not edit.",
       "// Maps qgl* calls onto the WebGPU fixed-function emulation (web/wgl_*.c).",
       "#ifndef __QGL_WGPU_H__", "#define __QGL_WGPU_H__", ""]
seen = set()
pat = r'extern\s+([A-Za-z_ ]+?\*?)\s*\(\s*APIENTRY\s*\*\s*qgl(\w+)\s*\)\s*\(([^;]*)\)\s*;'
for m in re.finditer(pat, src):
    ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
    if name in seen:
        continue
    seen.add(name)
    out.append(f"#define qgl{name} wg{name}")
    out.append(f"{ret} wg{name}( {args} );")
out += ["", '#include "wgl_engine.h"', "", "#endif", ""]
open(os.path.join(root, 'web/qgl_wgpu.h'), 'w').write("\n".join(out))
print(f"{len(seen)} entry points", file=sys.stderr)
